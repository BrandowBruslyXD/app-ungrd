/**
 * Busca un paquete por su código.
 *
 * Devuelve una copia para que aprobar un envío en la pantalla no mute los datos
 * sembrados y el paquete vuelva a su estado original al recargar la demostración.
 */
export function buscarPaquete(codigo: string): PaqueteMinisterio | null {
  const encontrado = paquetesSembrados.find(
    (paquete) => paquete.codigo.toUpperCase() === codigo.toUpperCase(),
  );
  if (!encontrado) return null;
  return { ...encontrado, danos: [...encontrado.danos], necesidades: [...encontrado.necesidades] };
}
